export type TermsType = 'base' | 'organizer' | 'agent';

export function getRequiredTermsTypes(role: string): TermsType[] {
  switch (role) {
    case 'artist':    return ['base'];
    case 'organizer': return ['base', 'organizer'];
    case 'agent':     return ['base', 'organizer', 'agent'];
    default:          return [];
  }
}

